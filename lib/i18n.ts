export const LOCALE_COOKIE = "tutorflow-locale";
export const DEFAULT_LOCALE = "en" as const;
export const SUPPORTED_LOCALES = ["en", "zh"] as const;

export type Locale = (typeof SUPPORTED_LOCALES)[number];

export function isLocale(value: string | null | undefined): value is Locale {
  return value === "en" || value === "zh";
}

export function setLocaleCookieDocument(locale: Locale): void {
  document.cookie = `${LOCALE_COOKIE}=${locale}; path=/; max-age=31536000; samesite=lax`;
  window.localStorage.setItem(LOCALE_COOKIE, locale);
}

export function replaceTemplate(input: string, values: Record<string, string | number>): string {
  return input.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? `{${key}}`));
}

export function toIntlLocale(locale: Locale): string {
  return locale === "zh" ? "zh-CN" : "en";
}

